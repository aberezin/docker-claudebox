import type { Command } from "../Command.ts";
import type { Context } from "../Context.ts";
import { DridockError } from "../../domain/errors.ts";
import { allVerbNames, verbsWithSubcommands } from "../../domain/Verbs.ts";

/**
 * `dridock completion bash` — emit a bash completion script. Ports
 * cb_completion_bash at wrapper.sh:1025. install.sh drops the output
 * into `~/.local/share/bash-completion/completions/<binname>`.
 */
/**
 * `start`'s completion offers the PROGRAMMATIC flags, which are not
 * `Verbs.ts` subcommands (there is no `dridock start list`) — they're the
 * allowlist the host layer validates `-p` runs against. So this one arm is
 * legitimately hand-maintained rather than generated, and is kept here,
 * named, instead of hiding inside the template as an unexplained literal.
 */
const START_FLAGS = [
  "-p", "--output-format", "--model", "--system-prompt", "--append-system-prompt",
  "--json-schema", "--effort", "--resume", "--no-continue", "--update",
].join(" ");

export class CompletionCommand implements Command {
  readonly verb = "completion" as const;
  readonly usage = `dridock completion bash

Emit a shell completion script. Add it to your shell rc to enable tab-completion.`;

  // Declared so #101's cross-check can compare this against `Verbs.ts`'s
  // `subcommands: ["bash"]`. Before this, `completion` declared no subverbs,
  // so UsageSubverbs.test.ts skipped it entirely — and the usage line above
  // advertised `[bash|zsh]` while the dispatcher threw a DridockError on
  // `zsh`. Declaring it is what makes that lie fail a test.
  readonly subverbs = [
    {
      name: "bash",
      synopsis: `dridock completion bash

Emit a bash completion script on stdout. Install it with:
  dridock completion bash > ~/.local/share/bash-completion/completions/dridock
zsh is not supported yet — this verb takes 'bash' and nothing else.`,
    },
  ] as const;

  async run(args: readonly string[], ctx: Context): Promise<number> {
    const shell = args[0];
    if (shell === undefined || shell === "") {
      ctx.stderr.write(`usage: ${ctx.binName} completion bash\n`);
      return 1;
    }
    if (shell !== "bash") {
      throw new DridockError(`completion: unsupported shell '${shell}' (bash only for now)`);
    }
    const prog = ctx.binName;
    const topVerbs = allVerbNames().join(" ");
    // Generated from Verbs.ts rather than hand-written beside it (#101).
    // Width-padded only for readability of the emitted script.
    const subcommandArms = verbsWithSubcommands()
      .map(([verb, subs]) => `        ${`${verb})`.padEnd(18)}COMPREPLY=( $(compgen -W "${subs.join(" ")}" -- "$cur") ) ;;\n`)
      .join("");
    // Static bash completion script — matches wrapper.sh:1027 shape.
    ctx.stdout.write(`# ${prog} bash completion — generated by \`${prog} completion bash\`.
# Install: ${prog} completion bash > ~/.local/share/bash-completion/completions/${prog}
_${prog}_complete() {
    local cur cword
    cur="\${COMP_WORDS[COMP_CWORD]}"
    cword=\$COMP_CWORD

    local top_verbs="${topVerbs}"

    if [ "\$cword" -eq 1 ]; then
        COMPREPLY=( \$(compgen -W "\$top_verbs" -- "\$cur") )
        return 0
    fi

    case "\${COMP_WORDS[1]}" in
${subcommandArms}        start)            COMPREPLY=( \$(compgen -W "${START_FLAGS}" -- "\$cur") ) ;;
    esac
}
complete -F _${prog}_complete ${prog}
`);
    return 0;
  }
}
